import { chromium, devices } from 'playwright';
const iPhone = devices['iPhone 12'];
const browser = await chromium.launch();
const context = await browser.newContext({ ...iPhone });
const page = await context.newPage();
await page.goto('http://localhost:8000/#about', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
const inner = await page.$eval('#main-container', el => el ? el.innerHTML : null);
console.log('MAIN CONTAINER LENGTH:', inner ? inner.length : 'NULL');
console.log(inner && inner.slice(0,800));
await browser.close();
process.exit(0);
